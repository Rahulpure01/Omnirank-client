/**
 * Builds ready-to-paste HTML meta tags based on SEO recommendations.
 */
export function generateMetaSnippet(report, url) {
  const title = report?.seo?.recommendedTitle || "Optimized Page Title";
  const desc = report?.seo?.recommendedDescription || "Optimized meta description for high CTR.";

  return `<!-- OmniRank SEO & Social Meta Tags -->
<title>${escapeHtml(title)}</title>
<meta name="description" content="${escapeHtml(desc)}" />
<link rel="canonical" href="${escapeHtml(url)}" />

<!-- Open Graph / Facebook -->
<meta property="og:type" content="website" />
<meta property="og:url" content="${escapeHtml(url)}" />
<meta property="og:title" content="${escapeHtml(title)}" />
<meta property="og:description" content="${escapeHtml(desc)}" />

<!-- Twitter Card -->
<meta name="twitter:card" content="summary_large_image" />
<meta name="twitter:title" content="${escapeHtml(title)}" />
<meta name="twitter:description" content="${escapeHtml(desc)}" />`;
}

/**
 * Generates an enriched Schema.org JSON-LD script block for AEO.
 */
export function generateSchemaScript(report, url) {
  const schemaType = report?.aeo?.suggestedSchemaType || "WebPage";
  const existingSchema = report?.aeo?.jsonLdSchema && Object.keys(report.aeo.jsonLdSchema).length > 0
    ? report.aeo.jsonLdSchema
    : {
        "@context": "https://schema.org",
        "@type": schemaType,
        "url": url,
        "name": report?.seo?.recommendedTitle || "",
        "description": report?.seo?.recommendedDescription || "",
        "about": report?.geo?.extractedEntities || []
      };

  return `<script type="application/ld+json">\n${JSON.stringify(existingSchema, null, 2)}\n</script>`;
}

/**
 * Formats full Tri-Engine audit report into downloadable Markdown.
 */
